#!/usr/bin/env python3
"""Embed human-readable factory JSON files as immutable application data."""
from __future__ import annotations

import argparse
import json
from pathlib import Path

DEFAULT_FILES = (
    "settings.json",
    "wifi.json",
    "sensors.json",
    "units.json",
    "webui-settings.json",
)


def load_defaults(directory: Path) -> dict[str, bytes]:
    result: dict[str, bytes] = {}
    for filename in DEFAULT_FILES:
        path = directory / filename
        raw = path.read_bytes()
        document = json.loads(raw.decode("utf-8"))
        schema_version = document.get("schemaVersion") if isinstance(document, dict) else None
        if isinstance(schema_version, bool) or not isinstance(schema_version, int) or schema_version != 1:
            raise ValueError(f"{path}: factory document must be an object with integer schemaVersion: 1")
        if b"\0" in raw:
            raise ValueError(f"{path}: NUL bytes are not valid in a JSON text file")
        result[filename] = raw
    return result


def byte_array(data: bytes) -> str:
    values = [f"0x{byte:02x}" for byte in data]
    values.append("0x00")
    lines = [", ".join(values[i:i + 16]) for i in range(0, len(values), 16)]
    return "{\n    " + ",\n    ".join(lines) + "\n}"


def generate(directory: Path, output: Path) -> None:
    defaults = load_defaults(directory)
    arrays: list[str] = []
    for filename, data in defaults.items():
        symbol = filename.replace("-", "_").replace(".", "_").upper()
        arrays.append(f"constexpr unsigned char {symbol}[] = {byte_array(data)};")

    cases = []
    for filename in defaults:
        symbol = filename.replace("-", "_").replace(".", "_").upper()
        cases.append(
            f'    if (std::strcmp(filename, "{filename}") == 0) '\
            f'return reinterpret_cast<const char *>({symbol});'
        )

    source = (
        '// Generated from assets/default/*.json. Do not edit this file.\n'
        '#include "factory_defaults.hpp"\n'
        '#include <cstring>\n\n'
        'namespace openscale::factory_defaults {\n'
        'namespace {\n'
        + "\n\n".join(arrays)
        + '\n} // namespace\n\n'
        'const char *get(const char *filename) noexcept {\n'
        '    if (!filename) return nullptr;\n'
        + "\n".join(cases)
        + '\n    return nullptr;\n'
        '}\n\n'
        '} // namespace openscale::factory_defaults\n'
    )
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(source, encoding="utf-8", newline="\n")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--defaults-dir", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    generate(args.defaults_dir.resolve(), args.output.resolve())
    print(f"Embedded {len(DEFAULT_FILES)} immutable factory JSON documents")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
